#!/usr/bin/env python3
"""Translate amiga-runtime declarative profiles into FS-UAE configuration."""
import os
import pathlib
import sys

if len(sys.argv) not in (7, 8):
    raise SystemExit("usage: generate-fs-uae-config.py PROFILE ROM EXT ISO FLOPPY OUTPUT [EVIDENCE_DIR]")

profile_path, rom, ext, iso, floppy, output = map(pathlib.Path, sys.argv[1:7])
evidence = pathlib.Path(sys.argv[7]) if len(sys.argv) == 8 else None
system_dir_env = os.environ.get("AMIGA_RUNTIME_AROS_SYSTEM_DIR")
system_dir = pathlib.Path(system_dir_env) if system_dir_env else None
values = {}
for raw in profile_path.read_text().splitlines():
    line = raw.strip()
    if not line or line.startswith("#"):
        continue
    key, sep, value = line.partition("=")
    if not sep:
        raise SystemExit(f"invalid profile line: {raw}")
    values[key.strip()] = value.strip()

machines = {"a500": "A500", "a500plus": "A500+", "a1200": "A1200", "a4000": "A4000"}
cpus = {"68000": "68000", "68020": "68020", "68030": "68030", "68040": "68040"}
try:
    model = machines[values["machine"]]
    cpu = cpus[values["cpu"]]
except KeyError as exc:
    raise SystemExit(f"unsupported profile value: {exc}")

chip_kib = int(values.get("chip_memory_kib", "2048"))
fast_kib = int(values.get("fast_memory_kib", "0"))
z3_kib = int(values.get("zorro_iii_memory_kib", "0"))
if chip_kib % 512:
    raise SystemExit("FS-UAE chip memory must be a multiple of 512 KiB")
if fast_kib % 1024:
    raise SystemExit("FS-UAE fast memory must be a multiple of 1024 KiB")
if z3_kib % 1024:
    raise SystemExit("FS-UAE Zorro III memory must be a multiple of 1024 KiB")

lines = [
    "# Generated by amiga-runtime; do not edit.",
    f"amiga_model = {model}",
    f"cpu = {cpu}",
    f"chip_memory = {chip_kib}",
    f"fast_memory = {fast_kib}",
    f"zorro_iii_memory = {z3_kib}",
    f"jit_compiler = {values.get('jit_compiler', '0')}",
    f"warp_mode = {values.get('warp_mode', '0')}",
    # FS-UAE internal Kickstart is the proven CI bootstrap used by AmiGuard.
    # The AROS m68k ROM pair is still acquired and hashed as runtime evidence,
    # but using it directly here makes FS-UAE 3.1.x exit during early startup.
    # Boot the extracted AROS/m68k system volume with the redistributable
    # internal replacement Kickstart instead.
    "kickstart_file = internal",
    "console_debugger = 0",
]
if system_dir is not None:
    lines.extend([
        f"hard_drive_0 = {system_dir}",
        "hard_drive_0_label = AROS",
        "hard_drive_0_read_only = 0",
        "hard_drive_0_priority = 10",
    ])
else:
    lines.extend([
        f"floppy_drive_0 = {floppy}",
        f"cdrom_drive_0 = {iso}",
    ])
if evidence is not None:
    drive = 1 if system_dir is not None else 0
    lines.extend([
        f"hard_drive_{drive} = {evidence}",
        f"hard_drive_{drive}_label = Evidence",
        f"hard_drive_{drive}_read_only = 0",
        f"hard_drive_{drive}_priority = -10",
    ])
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text("\n".join(lines) + "\n")
